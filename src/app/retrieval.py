# Embedding dimensionality generated by enrichment.py (gemini-embedding-001: 3072-d).
EMBEDDING_DIM = 3072

# Process-local cache of which meta tables exist. Assumes tables don't
# disappear mid-process (geometry.py/context.py rebuild them in a separate
# process). Call reset_meta_tables_cache() if a re-check is needed, e.g. in tests.
_META_TABLES_CACHE: set[str] | None = None


def _get_meta_tables(rag_con: duckdb.DuckDBPyConnection) -> set[str]:
    """Return which of building_geom_meta/building_context_meta/
    building_chunks_ruri_embed exist (queries the DB only on first call)."""
    global _META_TABLES_CACHE
    if _META_TABLES_CACHE is None:
        _META_TABLES_CACHE = set(rag_con.execute(
            "SELECT table_name FROM information_schema.tables "
            "WHERE table_name IN ('building_geom_meta', 'building_context_meta', "
            "'building_chunks_ruri_embed')"
        ).fetchdf()["table_name"])
    return _META_TABLES_CACHE


def reset_meta_tables_cache() -> None:
    """Discard the meta table existence cache (after geometry/context rebuilds, or for tests)."""
    global _META_TABLES_CACHE
    _META_TABLES_CACHE = None


