def _fmt_depth(v) -> str:
    """Format a flood depth value: NULL/NaN -> 'なし'."""
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "なし"
    return f"{v:.1f}"


def _fmt_height(v) -> str:
    """Format a height value: NULL/NaN/-9999.0 (sentinel invalid) -> '不明'."""
    if v is None or (isinstance(v, float) and pd.isna(v)) or v <= 0:
        return "不明"
    return f"{v:.1f}"


def _fmt_dist(v) -> str:
    """Format a distance value: NULL/NaN -> 'データなし'."""
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "データなし"
    return f"{v:.0f}"


def _fmt_plain(v) -> str:
    """Format a string column: NULL/NaN -> 'なし'."""
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "なし"
    return str(v)


def _fmt_unknown(v, fmt: str = "") -> str:
    """Format a value: NULL/NaN -> '不明' (used for roof_type_est/ground_elev_m)."""
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "不明"
    return format(v, fmt) if fmt else str(v)


def _fmt_storeys(v) -> str:
    """Format a storey count: NULL/NaN/>=500 (sentinel values like 9999) -> '不明'.

    The literal "9999階建て" that can appear inside `text_card` is out of
    scope here since that text is frozen in the DB (see limitations.md).
    """
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "不明"
    try:
        n = int(v)
    except (TypeError, ValueError):
        return "不明"
    return "不明" if n >= 500 or n < 0 else str(n)


def _fmt_ratio_pct(v) -> str:
    """Format a 0-1 ratio as 'N%'. NULL/NaN -> '不明'."""
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "不明"
    return f"{v * 100:.0f}%"


def _fmt_orientation(row) -> str:
    """Format all 4 wall orientation ratios compactly (e.g. 南30/北30/東20/西20).

    Showing only the dominant direction used to confuse users when the
    search condition (e.g. "south-facing") and the displayed value (e.g.
    "north is dominant by a hair") appeared to disagree, so this shows every
    direction instead. No data -> '不明'.
    """
    ratios = [
        ("南", row.get("wall_ratio_s")), ("北", row.get("wall_ratio_n")),
        ("東", row.get("wall_ratio_e")), ("西", row.get("wall_ratio_w")),
    ]
    parts = []
    for label, v in ratios:
        if v is None or (isinstance(v, float) and pd.isna(v)):
            continue
        parts.append(f"{label}{v * 100:.0f}")
    return "/".join(parts) if parts else "不明"


def _fmt_sunlit(v) -> str:
    """Format winter_sunlit (bool/NULL) as ○/×/不明."""
    if v is None or (isinstance(v, float) and pd.isna(v)):
        return "不明"
    return "○" if v else "×"


def build_prompt(query: str, candidates: pd.DataFrame, sort_by=None, response_language: str = "ja") -> str:
    """Build the prompt sent to the LLM.

    Args:
        query: The user's natural-language query.
        candidates: Candidate rows, in ranking order.
        sort_by: `query_parser.SortSpec | None`. Passed by `hybrid_search()`
            when `ParsedQuery.sort_by` was set by a superlative query (e.g.
            "the tallest"). When set, the prompt states explicitly that the
            comparison table is already in the requested order, and narrows
            the recommendation instruction to 1 pick (+2 runners-up).
        response_language: "ja" (default) or "en".

    The comparison table intentionally omits the raw similarity score and any
    "by similarity score" phrasing, to avoid anchoring the LLM on it — score
    is a weak upstream signal and shouldn't be presented as grounds for the
    final answer. Full `text_card` text is attached for only the top 10
    candidates; candidates beyond that appear as table rows only.

    The table's "dominant wall orientation" / "winter sunlight" / "roof" /
    "elevation (m)" columns, plus school/hospital/major-road distance, wooden
    density, and prominence, are all derived at prompt-build time from the
    candidate DataFrame's precomputed columns (`building_geom_meta`/
    `building_context_meta`) — `text_card` itself (frozen in the DB, paired
    with its embedding) is never modified for this.

    Returns:
        The complete prompt string.
    """
    n = len(candidates)

    # Comparison table (all candidates). The first column is the candidate
    # DataFrame's rank, which matches the GeoJSON feature's `rank` property.
    table_lines = [
        "| 順位 | 建物ID | 用途 | 高さ(m) | 階数 | 高潮浸水(m) | 洪水浸水(m) | "
        "津波浸水(m) | 構造 | 耐火 | 駅まで(m) | 避難所まで(m) | "
        "壁面方位(%) | 冬日照 | 屋根 | 形状 | 標高(m) | "
        "学校まで(m) | 病院まで(m) | 幹線道路まで(m) | 木造密度 | 突出(m) |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for i, (_, row) in enumerate(candidates.iterrows()):
        table_lines.append(
            f"| {i + 1} | {row['id']} | {_fmt_plain(row.get('usage'))} | "
            f"{_fmt_height(row.get('measured_height'))} | {_fmt_storeys(row.get('storeys'))} | "
            f"{_fmt_depth(row.get('ht_depth_max'))} | {_fmt_depth(row.get('rv_depth_max'))} | "
            f"{_fmt_depth(row.get('ts_depth_max'))} | {_fmt_plain(row.get('structure_type'))} | "
            f"{_fmt_plain(row.get('fire_proof'))} | {_fmt_dist(row.get('nearest_station_dist_m'))} | "
            f"{_fmt_dist(row.get('nearest_shelter_dist_m'))} | "
            f"{_fmt_orientation(row)} | {_fmt_sunlit(row.get('winter_sunlit'))} | "
            f"{_fmt_unknown(row.get('roof_type_est'))} | {_fmt_unknown(row.get('shape_type_est'))} | "
            f"{_fmt_unknown(row.get('ground_elev_m'), '.1f')} | "
            f"{_fmt_dist(row.get('nearest_school_dist_m'))} | {_fmt_dist(row.get('nearest_hospital_dist_m'))} | "
            f"{_fmt_dist(row.get('nearest_major_road_dist_m'))} | {_fmt_ratio_pct(row.get('wooden_density_ratio'))} | "
            f"{_fmt_unknown(row.get('prominence_m'), '.1f')} |"
        )
    table_str = "\n".join(table_lines)

    # text_card is frozen in the DB (paired with its embedding) and never
    # modified; precomputed columns are appended dynamically here instead.
    def _extra_info(row) -> str:
        parts = []
        for name_key, dist_key, label in [
            ("nearest_school_name",   "nearest_school_dist_m",   "最寄り学校"),
            ("nearest_hospital_name", "nearest_hospital_dist_m", "最寄り病院"),
            ("nearest_police_name",   "nearest_police_dist_m",   "最寄り警察署"),
            ("nearest_fire_name",     "nearest_fire_dist_m",     "最寄り消防署"),
            ("nearest_post_name",     "nearest_post_dist_m",     "最寄り郵便局"),
        ]:
            nm, dv = row.get(name_key), row.get(dist_key)
            if nm and not (isinstance(nm, float) and pd.isna(nm)) and dv is not None and not pd.isna(dv):
                parts.append(f"・{label}: {nm} 約 {dv:.0f}m")
        mr = row.get("nearest_major_road_dist_m")
        if mr is not None and not (isinstance(mr, float) and pd.isna(mr)):
            parts.append(f"・幹線道路（国道・県道）まで: 約 {mr:.0f}m")
        wd = row.get("wooden_density_ratio")
        if wd is not None and not (isinstance(wd, float) and pd.isna(wd)):
            parts.append(f"・周辺100m圏の木造建物比率: {wd * 100:.0f}%")
        pm = row.get("prominence_m")
        if pm is not None and not (isinstance(pm, float) and pd.isna(pm)):
            parts.append(f"・周囲最高建物との高低差（突出度）: {pm:+.1f}m")
        rt, ra = row.get("roof_type_est"), row.get("roof_area_m2")
        if rt and not (isinstance(rt, float) and pd.isna(rt)):
            ra_str = f"（屋根面積 約 {ra:.0f}m2）" if ra is not None and not pd.isna(ra) else ""
            parts.append(f"・屋根種別: {rt}{ra_str}")
        return "\n[追加情報（前計算）]\n" + "\n".join(parts) if parts else ""

    # Cap full text_card attachment to the top 10 candidates (shortens the
    # overall prompt).
    FULL_CARD_LIMIT = 10
    card_list = []
    for i, (_, row) in enumerate(candidates.iterrows()):
        if i >= FULL_CARD_LIMIT:
            break
        card_list.append(f"[{i + 1}] {row['text_card']}{_extra_info(row)}")
    cards_str = "\n---\n".join(card_list)
    omitted_note = (
        f"\n\n（{FULL_CARD_LIMIT + 1}件目以降 {n - FULL_CARD_LIMIT} 件は上記比較表のみ提示。詳細カルテは省略）"
        if n > FULL_CARD_LIMIT
        else ""
    )

    # When sort_by is set (a superlative query), state explicitly that the
    # table is already in the requested order, and narrow the recommendation
    # count to 1 pick + 2 runners-up.
    sort_note = (
        f"\n（この表は「{sort_by.key}」の{'降順' if sort_by.order == 'desc' else '昇順'}、"
        "つまり指定順に並んでいます）"
        if sort_by is not None
        else ""
    )
    # Fixes a bug where the LLM would recommend something other than table
    # rank 1 for superlative queries ("the tallest", etc.). When sort_by is
    # set, the table is already deterministically ordered by SQL's ORDER BY,
    # so the "selection" itself is fixed in code (rank 1/2/3's ids) rather
    # than left to the LLM's discretion — the LLM's role is limited to
    # explaining the reasoning.
    if sort_by is not None:
        top_id = candidates.iloc[0]["id"]
        runner_up_ids = candidates.iloc[1:3]["id"].tolist()
        fixed_recommendation_rule = (
            f"- 推薦する建物は必ず比較表1位の `{top_id}` とすること。"
            "他の建物を推薦してはならない（表は既に条件に基づき確定的に並んでいる）。"
            + (
                f" その後、次点として {', '.join(f'`{rid}`' for rid in runner_up_ids)} を"
                "簡潔に併記すること。"
                if runner_up_ids
                else ""
            )
        )
    else:
        fixed_recommendation_rule = "- 推薦する建物（最大 5 件）の建物ID と推薦理由"

    # Only the answer-language instruction switches; the comparison table and
    # detailed cards (Japanese data) are never translated — Gemini can
    # generate an English explanation from Japanese source data directly, so
    # translating the whole prompt isn't necessary. Explicitly says "concise"
    # rather than "detailed" per user feedback that answers were too long to
    # read comfortably.
    language_instruction = (
        "Please explain your recommendation in English, concisely."
        if response_language == "en"
        else "推薦理由を日本語で簡潔に説明してください。"
    )
    # Switch the heading text to match the response language too (previously
    # stayed as the Japanese "## 推薦する建物" even in the English UI).
    heading_label = "Recommended Building" if response_language == "en" else "推薦する建物"

    return f"""あなたは広島市の都市計画・防災アドバイザーです。
以下の建物カルテリストの中から、ユーザーの質問に最も合致する建物を選定し、
{language_instruction}

【ユーザーの質問】
{query}

【候補建物 比較表（上位 {n} 件）】{sort_note}
{table_str}

【候補建物 詳細カルテ】
{cards_str}{omitted_note}

【回答形式】
- 最初の1文目から `## {heading_label}` のように直接書き始めること。
  「〜アドバイザーとして」「ユーザーの『（質問文）』というご質問に対し」のような
  自己紹介・役割の名乗り・質問文の引用復唱は、1文字も書かないこと
- 見出しを使う場合は `##` 以下のレベルとし、`#` の最上位見出しは使わないこと
{fixed_recommendation_rule}
- 推薦理由は箇条書き2〜3点に絞ること。全属性を網羅的に列挙するのではなく、
  最も説得力のある根拠だけを選ぶこと
- 各理由は1〜2文の短い文で簡潔に述べ、1つの理由につき数値の根拠は1〜2個までとする
  （同じ観点を複数の言い回しで繰り返し説明しないこと）
- 入れ子の箇条書き（箇条書きの中にさらに箇条書き）は使わず、フラットな
  箇条書きで簡潔にまとめること
- 比較表の数値に基づき、ユーザーの質問の条件を実際に満たしているか確認してから推薦すること
- リスク値・距離などの具体的な数値を引用すること
- 方位・日照・静けさ・地形に関する推薦は、比較表の壁面方位・冬日照・標高・
  幹線道路距離等の数値を根拠として明示すること
- 学校・病院・警察署・消防署・郵便局など施設への近さに関する推薦は、
  [追加情報（前計算）] ブロックの施設名と距離を根拠として示すこと
- 表やカルテにない情報を創作しないこと
- 該当する建物が見つからない場合はその旨を述べること
- データの制限事項（コード値未解決など）があれば付記すること"""


def generate_answer(
    query: str,
    candidates: pd.DataFrame,
    sort_by=None,
    response_language: str = "ja",
) -> str:
    """Generate an answer to the user's query via Gemini 3.5 Flash Lite.

    Uses `GEMINI_API_KEY`. Retries up to 3 times.

    Args:
        query: The user's natural-language query.
        candidates: Candidate rows, in ranking order.
        sort_by: Forwarded to `build_prompt()`.
        response_language: "ja" (default) or "en", forwarded to `build_prompt()`.

    Returns:
        The generated answer text.

    Raises:
        RuntimeError: If all retries are exhausted.
    """
    prompt = build_prompt(query, candidates, sort_by=sort_by, response_language=response_language)

    for attempt in range(3):
        try:
            return _generate_with_gemini(prompt)
        except Exception as exc:
            if attempt == 2:
                raise RuntimeError(f"回答生成に失敗: {exc}") from exc
            wait = 3 * (attempt + 1)
            print(f"  [RETRY {attempt + 1}] {wait}秒後リトライ...")
            time.sleep(wait)


def _generate_with_gemini(prompt: str) -> str:
    """Generate an answer with Gemini 3.5 Flash Lite (temperature=0 for reproducibility)."""
    from google import genai
    from google.genai import types

    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        raise ValueError("GEMINI_API_KEY が .env に設定されていません。")

    client = genai.Client(api_key=api_key)
    response = client.models.generate_content(
        model="gemini-3.5-flash-lite",
        contents=prompt,
        config=types.GenerateContentConfig(temperature=0),
    )
    return response.text


# building_chunks.id format: a "bldg_" prefix + UUID (e.g. bldg_8aae00a2-e13d-4773-9c4f-51450c7963be).
_BUILDING_ID_PATTERN = re.compile(
    r"bldg_[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}"
)


def validate_answer(answer: str, candidates: pd.DataFrame, response_language: str = "ja") -> str:
    """Cross-check building IDs the LLM cited against the candidate set.

    Appends a note to the answer when it cites an ID absent from the
    candidates (a hallucination).

    Args:
        answer: The LLM's raw answer text.
        candidates: The candidate rows the answer was generated from.
        response_language: "ja" (default) or "en", for the appended note's language.

    Returns:
        `answer`, with a hallucination-warning note appended if applicable.
    """
    if not answer or candidates.empty:
        return answer

    mentioned_ids = set(_BUILDING_ID_PATTERN.findall(answer))
    if not mentioned_ids:
        return answer

    valid_ids = set(candidates["id"].tolist())
    unknown_ids = mentioned_ids - valid_ids
    if not unknown_ids:
        return answer

    # Switch the note's wording to match the response language too.
    if response_language == "en":
        note = (
            f"\n\n※ Note: The building ID(s) {', '.join(sorted(unknown_ids))} mentioned "
            "above are not in the search candidates. This may indicate a data error."
        )
    else:
        note = (
            f"\n\n※ 注記: 回答中の建物ID {', '.join(sorted(unknown_ids))} は"
            "検索候補に含まれていません。データの誤りの可能性があるためご注意ください。"
        )
    print(f"  [validate_answer] 候補に存在しない建物IDを検出: {unknown_ids}")
    return answer + note


