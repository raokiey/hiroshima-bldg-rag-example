def hybrid_search(
    query: str,
    lon: float | None = None,
    lat: float | None = None,
    radius_m: float = 500.0,
    top_k: int = 30,
    use_query_parser: bool = True,
    skip_answer: bool = False,
    use_fts: bool = False,
    use_hyde: bool = False,
    embedding_source: str = "ruri",
    parsed_query_override: "ParsedQuery | None" = None,
    response_language: str = "ja",
) -> dict:
    """The integrated hybrid search API — this is the module's main entry point.

    When `use_query_parser=True` (default):
      1. Get a `ParsedQuery` from `parse_query(query)` (LLM query parsing).
      2. If `clarification_question` is set, skip search and return the question.
      3. If lon/lat weren't given but `location_name` was, resolve it via `geocode()`.
      4. Pass the ParsedQuery's filters into `vector_search()`.

    When `use_query_parser=False`: behaves as before query parsing existed
    (backward compatibility).

    Args:
        query: The natural-language query.
        lon: Search center longitude (WGS84). None means no spatial filter
            unless auto-geocoded via `location_name`.
        lat: Search center latitude (WGS84).
        radius_m: Spatial filter radius in meters.
        top_k: Number of candidates to fetch.
        use_query_parser: Enable LLM query parsing and geocoding.
        skip_answer: Skip LLM answer generation and return `answer=""` (used
            by evaluation scripts to conserve API quota).
        use_fts: Fuse BM25 full-text search with vector search via RRF
            (disabled for route="structured").
        use_hyde: Rewrite the semantic residual into a hypothetical card text
            before embedding (disabled for route="structured").
        embedding_source: "ruri" (default) or "gemini". "ruri" uses RURI v3
            310m (`embed_query_ruri`) for the query embedding and has
            `vector_search()` reference `building_chunks_ruri_embed`. Being
            local inference, it skips the ~1.25s API round trip — about
            0.085s once warm.
        parsed_query_override: When given, skips calling `parse_query(query)`
            and uses this `ParsedQuery` directly instead. An evaluation-only
            hook for fairly comparing `embedding_source="gemini"` vs `"ruri"`
            against the same parse result. None (default) calls
            `parse_query()` internally as usual.
        response_language: "ja" (default) or "en", forwarded to `build_prompt()`.

    Returns:
        A dict with `query`, `candidates`, `answer`, `elapsed_sec`,
        `parsed_query`, `geocoded_location`, `clarification_question`, `route`.
    """
    t0 = time.time()
    parsed_query_dict: dict | None = None
    geocoded_location: dict | None = None

    print(f"\n  クエリ: {query}")

    # =====================================================================
    # Query parsing / geocoding, then routing
    # =====================================================================
    from src.app.query_parser import parse_query, ParsedQuery
    from src.app.geocoder import geocode
    from src.app.router import classify_route

    search_lon = lon
    search_lat = lat
    search_radius = radius_m

    if use_query_parser:
        if parsed_query_override is not None:
            pq = parsed_query_override
            print("  クエリ解析: 既存のParsedQueryを再利用（parsed_query_override指定）")
        else:
            print("  クエリ解析中...")
            pq = parse_query(query, response_language=response_language)
        parsed_query_dict = {
            "location_name":          pq.location_name,
            "radius_m":               pq.radius_m,
            "height_min":             pq.height_min,
            "usage_include":          pq.usage_include,
            "structure_type":         pq.structure_type,
            "sort_by_height":         pq.sort_by_height,
            "clarification_question": pq.clarification_question,
            "risk_filters":           [vars(rf) for rf in pq.risk_filters],
            "distance_filters":       [vars(df) for df in pq.distance_filters],
            "fire_proof":             pq.fire_proof,
            "sort_by":                (vars(pq.sort_by) if pq.sort_by else None),
            "semantic_residual":      pq.semantic_residual,
            "orientation_filters":    [vars(of) for of in pq.orientation_filters],
            "sunlight":               pq.sunlight,
            "quiet":                  pq.quiet,
            "vertical_evacuation":    pq.vertical_evacuation,
            "height_max":             pq.height_max,
            "storeys_min":            pq.storeys_min,
            "storeys_max":            pq.storeys_max,
            "usage_exclude":          pq.usage_exclude,
            "structure_exclude":      pq.structure_exclude,
            "roof_type":              pq.roof_type,
            "wooden_dense":           pq.wooden_dense,
            "footprint_shape":        pq.footprint_shape,
        }
        print(f"  解析結果: location={pq.location_name}, height_min={pq.height_min}, "
              f"sort_by={pq.sort_by}, usage={pq.usage_include}, "
              f"structure={pq.structure_type}, risk_filters={pq.risk_filters}, "
              f"distance_filters={pq.distance_filters}, semantic_residual={pq.semantic_residual!r}")

        # If there's a clarification question, skip search and return it.
        if pq.clarification_question:
            print(f"  確認質問を返します: {pq.clarification_question[:50]}...")
            return {
                "query": query,
                "candidates": pd.DataFrame(),
                "answer": pq.clarification_question,
                "elapsed_sec": time.time() - t0,
                "parsed_query": parsed_query_dict,
                "geocoded_location": None,
                "clarification_question": pq.clarification_question,
                "route": None,
            }

        # Only auto-geocode when lon/lat weren't given manually.
        if search_lon is None and pq.location_name:
            coords = geocode(pq.location_name)
            if coords is not None:
                search_lon, search_lat = coords
                search_radius = pq.radius_m
                geocoded_location = {"lon": search_lon, "lat": search_lat}
        elif search_lon is not None:
            # Manual coordinates take precedence as-is (radius_m too).
            geocoded_location = {"lon": search_lon, "lat": search_lat}
    else:
        # Backward compat: behave as before query parsing existed (route is
        # always fixed to "semantic").
        pq = ParsedQuery()

    route = classify_route(pq) if use_query_parser else "semantic"
    print(f"  検索経路: {route}")
    print(f"  空間フィルタ: {'あり (lon={:.4f}, lat={:.4f}, r={}m)'.format(search_lon, search_lat, search_radius) if search_lon is not None else 'なし'}")

    # =====================================================================
    # Step 1: Embed the query (no API call when route="structured")
    # =====================================================================
    fts_query_text: str | None = None
    if route == "structured":
        query_vec = None
        print("  埋め込み生成をスキップ（route=structured）")
    else:
        embed_text = pq.semantic_residual if (use_query_parser and pq.semantic_residual) else query
        fts_query_text = embed_text
        if use_hyde:
            from src.app.search_fusion import hyde_rewrite
            print("  HyDE書き換え中...")
            hyde_text = hyde_rewrite(embed_text)
            print(f"  HyDE書き換え結果: {hyde_text!r}")
            embed_text = hyde_text
        print("  クエリ埋め込み生成中...")
        if embedding_source == "ruri":
            from src.app.ruri_query import embed_query_ruri
            query_vec = embed_query_ruri(embed_text)
        else:
            query_vec = embed_query(embed_text)

    # =====================================================================
    # Step 2: Vector search (HNSW + optional spatial filter + attribute filters)
    # =====================================================================
    print("  検索中...")
    rag_con = connect_rag()
    try:
        candidates = vector_search(
            rag_con, pq, route, query_vec,
            lon=search_lon, lat=search_lat, radius_m=search_radius, top_k=top_k,
            use_fts=use_fts, fts_query_text=fts_query_text,
            embedding_source=embedding_source,
        )
    finally:
        rag_con.close()

    print(f"  候補建物: {len(candidates)} 件")

    # Defensive re-check after the SQL filter (drops any candidates violating
    # a condition — see router.verify_candidates for why this is needed).
    from src.app.router import verify_candidates
    candidates, _removed_reasons = verify_candidates(candidates, pq)
    print(f"  検証後候補建物: {len(candidates)} 件")

    if candidates.empty:
        return {
            "query": query,
            "candidates": candidates,
            "answer": (
                "No matching buildings were found. Please modify your query or search area."
                if response_language == "en"
                else "候補建物が見つかりませんでした。クエリや検索範囲を変更してください。"
            ),
            "elapsed_sec": time.time() - t0,
            "parsed_query": parsed_query_dict,
            "geocoded_location": geocoded_location,
            "clarification_question": None,
            "route": route,
            "embedding_source": embedding_source,
            "response_language": response_language,
        }

    # =====================================================================
    # Step 3: LLM answer generation (temperature=0 for reproducibility)
    # =====================================================================
    if skip_answer:
        answer = ""
        print("  回答生成をスキップ（skip_answer=True）")
    else:
        print("  回答生成中（gemini）...")
        answer = generate_answer(
            query, candidates, sort_by=pq.sort_by,
            response_language=response_language,
        )
        answer = validate_answer(answer, candidates, response_language=response_language)

        # Post-hoc check for superlative queries (sort_by set): logs a
        # warning if the LLM recommended something other than table rank 1,
        # without modifying the answer itself.
        if pq.sort_by is not None:
            mentioned_ids = _BUILDING_ID_PATTERN.findall(answer)
            expected_top_id = candidates.iloc[0]["id"]
            if mentioned_ids and mentioned_ids[0] != expected_top_id:
                print(
                    f"  [WARN] sort_by指定クエリで比較表1位（{expected_top_id}）以外の"
                    f"建物（{mentioned_ids[0]}）が回答冒頭で言及されました"
                )

    elapsed = time.time() - t0
    print(f"  完了: {elapsed:.1f} 秒")

    return {
        "query": query,
        "candidates": candidates,
        "answer": answer,
        "elapsed_sec": elapsed,
        "parsed_query": parsed_query_dict,
        "geocoded_location": geocoded_location,
        "clarification_question": None,
        "route": route,
        "embedding_source": embedding_source,
        "response_language": response_language,
    }


