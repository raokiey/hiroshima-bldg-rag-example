"""Hybrid search engine: spatial filter x vector search x LLM answer generation.

Processing flow:
  1. Embed the query text with RURI v3 310m (default, local) or
     `gemini-embedding-001`.
  2. Extract top-K candidates via DuckDB HNSW `array_cosine_similarity`
     (adds an `ST_DWithin` spatial filter when lon/lat are given).
  3. Rerank candidate cards and generate an answer with Gemini 3.5 Flash Lite.

`use_query_parser=True` (default) enables LLM query parsing and geocoding: a
`clarification_question` skips search and returns the question directly;
`height_min` / `usage_include` / `structure_type` / `sort_by_height`
attribute filters are supported; answer generation uses temperature=0 for
reproducibility.

`classify_route()` splits a query into structured/semantic/hybrid routes
based on its structured conditions and semantic residual, and optimizes the
search/embedding calls per route — the structured route skips the embedding
API entirely and resolves purely via SQL.
"""

