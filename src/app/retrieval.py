def embed_query(text: str) -> list[float]:
    """Embed query text with `gemini-embedding-001`.

    Uses `task_type="RETRIEVAL_QUERY"` (as opposed to `RETRIEVAL_DOCUMENT`,
    used by `enrichment.py` for the document side).

    Args:
        text: The query text.

    Returns:
        A list of `EMBEDDING_DIM` floats.

    Raises:
        RuntimeError: If all retries are exhausted.
    """
    from google import genai
    from google.genai import types

    api_key = os.getenv("GEMINI_API_KEY")
    if not api_key:
        raise ValueError("GEMINI_API_KEY が .env に設定されていません。")

    client = genai.Client(api_key=api_key)

    for attempt in range(3):
        try:
            response = client.models.embed_content(
                model="gemini-embedding-001",
                contents=[text],
                config=types.EmbedContentConfig(task_type="RETRIEVAL_QUERY"),
            )
            return list(response.embeddings[0].values)
        except Exception as exc:
            if attempt == 2:
                raise RuntimeError(f"クエリ埋め込み生成に失敗: {exc}") from exc
            wait = 3 * (attempt + 1)
            print(f"  [RETRY {attempt + 1}] {wait}秒後リトライ...")
            time.sleep(wait)


def vector_search(
    rag_con: duckdb.DuckDBPyConnection,
    pq: "ParsedQuery",
    route: str,
    query_vec: list[float] | None,
    lon: float | None = None,
    lat: float | None = None,
    radius_m: float = 500.0,
    top_k: int = 30,
    use_fts: bool = False,
    fts_query_text: str | None = None,
    embedding_source: str = "ruri",
) -> pd.DataFrame:
    """Run the search matching one of the three routes: structured/semantic/hybrid.

    - route="structured": expects `query_vec=None`. Resolves purely via SQL
      (WHERE filter + ORDER BY), no embedding API call. `score` is NULL.
    - route="semantic": vector search over all rows (or the spatial-filtered
      subset), as before.
    - route="hybrid": ranks by `array_cosine_similarity` after applying
      `build_filter_clauses()`'s WHERE filter (HNSW doesn't help once
      filtered — this becomes a brute-force scan, which is fine at 2,958 rows).

    A spatial filter (when lon/lat are given) applies via `ST_DWithin`
    regardless of route.

    When `use_fts=True` and route is semantic/hybrid, fetches `top_k*2`
    vector results, fuses them with `fts_search()`'s BM25 results via
    `rrf_merge()`, and trims to the top `top_k` (`fts_query_text` required).

    When `pq` specifies fields that need `building_geom_meta`
    (orientation_filters/sunlight/roof_type/...) or `building_context_meta`
    (quiet/wooden_dense/school distance_filters/...) but the table doesn't
    exist, raises `RuntimeError` rather than silently ignoring the condition.

    When `embedding_source="ruri"`, left-joins `building_chunks_ruri_embed`
    (RURI v3 310m, 768-d) instead of scoring against `building_chunks.embedding`
    (gemini-embedding-001, 3072-d); `building_chunks` and its HNSW index are
    never touched by this branch.

    Args:
        rag_con: An open connection from `connect_rag()`.
        pq: The parsed query.
        route: One of "structured"/"semantic"/"hybrid", from `classify_route()`.
        query_vec: The query embedding, or None for route="structured".
        lon: Optional spatial filter center longitude (WGS84).
        lat: Optional spatial filter center latitude (WGS84).
        radius_m: Spatial filter radius in meters.
        top_k: Number of candidates to return.
        use_fts: Whether to fuse in BM25 full-text search results.
        fts_query_text: Required when `use_fts=True`.
        embedding_source: "ruri" (default) or "gemini".

    Returns:
        A DataFrame of candidate rows with a `score` column (NULL for
        route="structured"), ordered per `build_order_clause()`.

    Raises:
        RuntimeError: If a required precomputed table is missing.
    """
    from src.app.router import build_filter_clauses, build_order_clause, COLUMN_SOURCE

    fetch_k = top_k * 2 if (use_fts and route != "structured") else top_k

    use_vector = route != "structured"
    if use_vector:
        assert query_vec is not None, "route != 'structured' の場合 query_vec が必須です"
        dim = len(query_vec)
        qvec = np.array(query_vec, dtype=np.float32)
    else:
        dim = EMBEDDING_DIM

    # Check which meta tables exist (process-local cache after first query).
    existing_tables = _get_meta_tables(rag_con)
    has_geom_meta = "building_geom_meta" in existing_tables
    has_context_meta = "building_context_meta" in existing_tables
    has_ruri_embed = "building_chunks_ruri_embed" in existing_tables

    # Raise explicitly when a field requires a precomputed table that doesn't exist.
    _context_targets = {"school", "hospital", "police", "fire", "post"}
    needs_geom = bool(
        pq.orientation_filters or pq.roof_type
        or (pq.sunlight)
        or (pq.sort_by and COLUMN_SOURCE.get(pq.sort_by.key) == "g")
    )
    needs_context = bool(
        pq.sunlight or pq.quiet or pq.wooden_dense
        or any(df.target in _context_targets for df in pq.distance_filters)
        or (pq.sort_by and COLUMN_SOURCE.get(pq.sort_by.key) == "c")
    )
    if needs_geom and not has_geom_meta:
        raise RuntimeError(
            "building_geom_meta が存在しません。先に "
            "`pixi run python -m src.pipeline.geometry` を実行してください。"
        )
    if needs_context and not has_context_meta:
        raise RuntimeError(
            "building_context_meta が存在しません。先に "
            "`pixi run python -m src.pipeline.context` を実行してください。"
        )

    use_ruri = use_vector and embedding_source == "ruri"
    if use_ruri and not has_ruri_embed:
        raise RuntimeError(
            "building_chunks_ruri_embed が存在しません。先に "
            "`pixi run python -m src.pipeline.ruri_embed` を実行してください。"
        )

    if not use_vector:
        score_expr = "NULL AS score"
    elif use_ruri:
        score_expr = f"array_cosine_similarity(r.embedding, ?::FLOAT[{dim}]) AS score"
    elif has_geom_meta:
        score_expr = f"array_cosine_similarity(b.embedding, ?::FLOAT[{dim}]) AS score"
    else:
        score_expr = f"array_cosine_similarity(embedding, ?::FLOAT[{dim}]) AS score"

    # Column selection (geometry omitted to keep the payload light).
    if has_geom_meta and has_context_meta:
        select_cols = f"""
            b.id, b.text_card, b.usage, b.measured_height, b.storeys,
            b.ht_depth_max, b.ht_rank_worst,
            b.rv_depth_max, b.rv_rank_worst,
            b.ts_depth_max, b.ts_rank_worst,
            b.structure_type, b.fire_proof,
            b.nearest_shelter_name, b.nearest_shelter_dist_m,
            b.nearest_station_name, b.nearest_station_dist_m,
            b.nearest_emroute_name, b.nearest_emroute_dist_m,
            b.nearest_park_name, b.nearest_park_dist_m,
            b.nearest_landmark_name, b.nearest_landmark_dist_m,
            {score_expr},
            g.ground_elev_m, g.building_height_m, g.roof_area_m2, g.roof_type_est,
            g.wall_ratio_n, g.wall_ratio_e, g.wall_ratio_s, g.wall_ratio_w,
            g.shape_type_est,
            c.winter_sunlit, c.prominence_m, c.wooden_density_ratio, c.nearest_major_road_dist_m,
            c.nearest_school_name, c.nearest_school_dist_m,
            c.nearest_hospital_name, c.nearest_hospital_dist_m,
            c.nearest_police_name, c.nearest_police_dist_m,
            c.nearest_fire_name, c.nearest_fire_dist_m,
            c.nearest_post_name, c.nearest_post_dist_m
        """
        from_clause = (
            "FROM building_chunks b "
            "LEFT JOIN building_geom_meta g ON b.id = g.id "
            "LEFT JOIN building_context_meta c ON b.id = c.id"
        )
        alias = "b."
        table_aliases = {"b": "b.", "g": "g.", "c": "c."}
    elif has_geom_meta:
        select_cols = f"""
            b.id, b.text_card, b.usage, b.measured_height, b.storeys,
            b.ht_depth_max, b.ht_rank_worst,
            b.rv_depth_max, b.rv_rank_worst,
            b.ts_depth_max, b.ts_rank_worst,
            b.structure_type, b.fire_proof,
            b.nearest_shelter_name, b.nearest_shelter_dist_m,
            b.nearest_station_name, b.nearest_station_dist_m,
            b.nearest_emroute_name, b.nearest_emroute_dist_m,
            b.nearest_park_name, b.nearest_park_dist_m,
            b.nearest_landmark_name, b.nearest_landmark_dist_m,
            {score_expr},
            g.ground_elev_m, g.building_height_m, g.roof_area_m2, g.roof_type_est,
            g.wall_ratio_n, g.wall_ratio_e, g.wall_ratio_s, g.wall_ratio_w,
            g.shape_type_est
        """
        from_clause = "FROM building_chunks b LEFT JOIN building_geom_meta g ON b.id = g.id"
        alias = "b."
        table_aliases = {"b": "b.", "g": "g.", "c": "b."}
    else:
        select_cols = f"""
            id, text_card, usage, measured_height, storeys,
            ht_depth_max, ht_rank_worst,
            rv_depth_max, rv_rank_worst,
            ts_depth_max, ts_rank_worst,
            structure_type, fire_proof,
            nearest_shelter_name, nearest_shelter_dist_m,
            nearest_station_name, nearest_station_dist_m,
            nearest_emroute_name, nearest_emroute_dist_m,
            nearest_park_name, nearest_park_dist_m,
            nearest_landmark_name, nearest_landmark_dist_m,
            {score_expr}
        """
        from_clause = "FROM building_chunks"
        alias = ""
        table_aliases = {"b": "", "g": "", "c": ""}

    if use_ruri:
        from_clause += f" LEFT JOIN building_chunks_ruri_embed r ON {alias}id = r.id"

    # Convert the parsed query's structured conditions into WHERE/ORDER BY clauses.
    where_extra, params_extra = build_filter_clauses(pq, alias=alias, table_aliases=table_aliases)
    order_clause = build_order_clause(pq, route, alias=alias, table_aliases=table_aliases)

    params_head = [qvec] if use_vector else []

    if lon is not None and lat is not None:
        # Spatial filter requested: convert WGS84 -> EPSG:6671.
        tmp_con = connect_gpkg()
        x, y = wgs84_to_epsg6671(tmp_con, lon, lat)
        tmp_con.close()

        extra_where = ("AND " + " AND ".join(where_extra)) if where_extra else ""
        sql = f"""
        SELECT {select_cols}
        {from_clause}
        WHERE ST_DWithin({alias}geometry, ST_Point(?, ?), ?)
        {extra_where}
        {order_clause}
        LIMIT ?
        """
        df = rag_con.execute(sql, params_head + [x, y, radius_m] + params_extra + [fetch_k]).df()
    else:
        # No spatial filter: search all rows (structured/hybrid narrow via
        # the WHERE filter alone).
        extra_where = ("WHERE " + " AND ".join(where_extra)) if where_extra else ""
        sql = f"""
        SELECT {select_cols}
        {from_clause}
        {extra_where}
        {order_clause}
        LIMIT ?
        """
        df = rag_con.execute(sql, params_head + params_extra + [fetch_k]).df()

    # Fuse in BM25 full-text search via RRF (not applied for route="structured").
    # Simplification by design: fts_df is narrowed to the id set already
    # fetched by vector search before merging — i.e. FTS is only used to
    # re-rank existing candidates, never to introduce ids the vector search
    # missed. This avoids candidates with missing columns (text_card etc.)
    # that would occur for rows FTS matched but vector search didn't.
    if use_fts and route != "structured" and fts_query_text and not df.empty:
        from src.app.search_fusion import ensure_fts_index, fts_search, rrf_merge
        # Check for the tokenized FTS table (building_chunks_fts).
        has_fts_index = rag_con.execute(
            "SELECT COUNT(*) FROM information_schema.schemata "
            "WHERE schema_name = 'fts_main_building_chunks_fts'"
        ).fetchone()[0] > 0
        if not has_fts_index:
            print("  FTS インデックス未作成のため作成中...")
            ensure_fts_index(rag_con)
        fts_df = fts_search(rag_con, fts_query_text, top_k=fetch_k)
        fts_df = fts_df[fts_df["id"].isin(set(df["id"]))].reset_index(drop=True)
        if not fts_df.empty:
            df = rrf_merge(df, fts_df, id_col="id")
        df = df.head(top_k).reset_index(drop=True)

    return df


