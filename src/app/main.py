@asynccontextmanager
async def lifespan(app: FastAPI):
    """Pre-load the RURI v3 310m model (~11s) at server startup.

    Without this, since the default `embedding_source="ruri"`, the first
    semantic/hybrid search query of a demo would eat that 11s load cost live.
    Failures here don't block startup — the model just loads normally on the
    first query instead.
    """
    try:
        from src.app.ruri_query import embed_query_ruri
        embed_query_ruri("ウォームアップ")
        print("[startup] RURI v3 310m のプリウォーム完了")
    except Exception as exc:
        print(f"[startup] RURI プリウォーム失敗（初回クエリ時にロードされます）: {exc}")
    yield


app = FastAPI(title="PLATEAU RAG API", version="1.0.0", lifespan=lifespan)

