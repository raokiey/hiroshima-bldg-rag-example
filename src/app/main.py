@app.get("/api/health")
async def health():
    """Check whether the RAG database file exists."""
    return {
        "status": "ok",
        "db_exists": RAG_DB_PATH.exists(),
        "db_path": str(RAG_DB_PATH),
    }


@app.post("/api/search", response_model=SearchResponse)
async def search(req: SearchRequest):
    """The hybrid search endpoint.

    `hybrid_search()` is synchronous, so it's wrapped via `run_in_executor` to
    avoid blocking the event loop.
    """
    if not req.query.strip():
        detail = (
            "Please enter a query."
            if req.response_language == "en"
            else "クエリを入力してください。"
        )
        raise HTTPException(status_code=400, detail=detail)

    loop = asyncio.get_event_loop()
    try:
        result = await loop.run_in_executor(
            None,
            partial(
                hybrid_search,
                query=req.query,
                lon=req.lon,
                lat=req.lat,
                radius_m=req.radius_m,
                top_k=req.top_k,
                use_query_parser=req.use_query_parser,
                embedding_source=req.embedding_source,
                response_language=req.response_language,
            ),
        )
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))

    # Recommended-ID extraction must happen before GeoJSON conversion, since
    # candidates_to_geojson() needs it to set each feature's is_recommended flag.
    candidates = result["candidates"]
    candidate_id_set = set(candidates["id"]) if candidates is not None and not candidates.empty else set()
    recommended_ids = extract_recommended_ids(result["answer"], candidate_id_set)

    geojson = candidates_to_geojson(candidates, recommended_ids=recommended_ids)

    return SearchResponse(
        query=result["query"],
        answer=result["answer"],
        elapsed_sec=round(result["elapsed_sec"], 2),
        geojson=geojson,
        candidate_count=len(geojson["features"]),
        parsed_query=result.get("parsed_query"),
        geocoded_location=result.get("geocoded_location"),
        clarification_question=result.get("clarification_question"),
        route=result.get("route"),
        recommended_ids=recommended_ids,
        embedding_source=result.get("embedding_source", "ruri"),
        response_language=result.get("response_language", "ja"),
    )


